// ── Canvas ────────────────────────────────────────────────────────────────────
const SCALE     = 2;
const PAD       = 14;
const CARD_W    = 194;
const CARD_H    = 90;
const CARD_GAP  = 5;
const COLS      = 5;
const GRID_W    = COLS * CARD_W + (COLS - 1) * CARD_GAP;
const PROFILE_H = 84;       // top profile header
const FOOTER_H  = 20;       // "generated by moimoi" line
// B15 = 3 rows, B35 = 7 rows, each section preceded by a 28px label pill
const GRID_H    = 28 + 3 * (CARD_H + CARD_GAP) + 10 + 28 + 7 * (CARD_H + CARD_GAP) - CARD_GAP;
