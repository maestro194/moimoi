const JS = CA - JP * 2;     // square jacket size (= 58)
const RB_W = 52, RB_H = 28; // rating box

// Per-difficulty card theme. REMAS is the one light card (dark text), as in the reference design.
interface CardTheme {
  body: string; strip: string; text: string;
  ratingBg: string; ratingFg: string;
  levelBg: string; levelFg: string;
  light: boolean;
}
const darkTheme = (body: string, strip: string): CardTheme => ({
  body, strip, text: "#ffffff",
  ratingBg: "rgba(0,0,0,0.28)", ratingFg: "#ffffff",
  levelBg: "#ffffff", levelFg: "#1a1424",
  light: false,
});
const CARD_THEME: Record<string, CardTheme> = {
  BAS:   darkTheme("#2c5a33", "#3a7343"),
  ADV:   darkTheme("#6a4a12", "#85601c"),
  EXP:   darkTheme("#5e2c2c", "#7c3838"),
  MAS:   darkTheme("#412959", "#5a387c"),
  REMAS: {
    body: "#9c85b2", strip: "#c3add9", text: "#2a2035",
    ratingBg: "#c3add9", ratingFg: "#2a2035",
    levelBg: "#32293b", levelFg: "#ffffff",
    light: true,
  },
  UTAGE: darkTheme("#5a1f40", "#752a55"),
};

