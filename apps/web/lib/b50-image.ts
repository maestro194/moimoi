// ── Font ──────────────────────────────────────────────────────────────────────
let fontsReady = false;

// All text — M PLUS Rounded 1c Bold (Maru Gothic substitute)
const F  = (px: number) =>
  `${px}px "MPlusRoundedBold", "MPlusRounded", "NotoSansJP", "Meiryo", sans-serif`;

// Rank glyphs (S, A …) only — M PLUS Rounded 1c Black
const FH = (px: number) =>
  `${px}px "MPlusRounded", "NotoSansJP", "Meiryo", sans-serif`;


async function setupFonts(): Promise<void> {
  if (fontsReady) return;
  fontsReady = true;

  // 1. Nunito variable TTF (Avenir Next Heavy substitute — alphanumerics)
  const nunitoPath = path.join(process.cwd(), "public", "fonts", "Nunito-VF.ttf");
  try { await fs.access(nunitoPath); GlobalFonts.registerFromPath(nunitoPath, "Nunito"); }
  catch { /* missing — falls back to system fonts */ }

  // 2. M PLUS Rounded 1c — Bold for text, Black for rank glyphs (Maru Gothic substitute)
  const mplusPath = path.join(process.cwd(), "public", "fonts", "MPlusRounded1c-Black.ttf");
  try { await fs.access(mplusPath); GlobalFonts.registerFromPath(mplusPath, "MPlusRounded"); }
  catch { /* missing — FH will fall back to NotoSansJP */ }
  const mplusBoldPath = path.join(process.cwd(), "public", "fonts", "MPlusRounded1c-Bold.ttf");
  try { await fs.access(mplusBoldPath); GlobalFonts.registerFromPath(mplusBoldPath, "MPlusRoundedBold"); }
  catch { /* missing — F falls back to the Black face */ }

  // 3. Noto Sans JP fallback for any remaining Japanese glyphs
  const fontCacheDir = path.join(process.cwd(), ".next", "cache", "fonts");
  await fs.mkdir(fontCacheDir, { recursive: true }).catch(() => {});
  const candidates = [
    path.join(process.cwd(), "public", "fonts", "NotoSansJP-Regular.ttf"),
    path.join(process.cwd(), "public", "fonts", "NotoSansJP.ttf"),
    path.join(fontCacheDir, "NotoSansJP.ttf"),
    "C:\\Windows\\Fonts\\meiryo.ttc",
    "C:\\Windows\\Fonts\\YuGothM.ttc",
    "C:\\Windows\\Fonts\\YuGothR.ttc",
    "C:\\Windows\\Fonts\\msgothic.ttc",
    "/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc",
    "/usr/share/fonts/truetype/noto/NotoSansCJKjp-Regular.ttf",
    "/usr/share/fonts/noto-cjk/NotoSansCJK-Regular.ttc",
  ];
  for (const p of candidates) {
    try { await fs.access(p); GlobalFonts.registerFromPath(p, "NotoSansJP"); return; }
    catch { /* next */ }
  }
  try {
    const url = "https://raw.githubusercontent.com/notofonts/noto-cjk/main/Sans/Variable/TTF/Subset/NotoSansJP-VF.ttf";
    const res = await fetch(url, { signal: AbortSignal.timeout(60_000) });
    if (res.ok) {
      const p = path.join(fontCacheDir, "NotoSansJP.ttf");
      await fs.writeFile(p, Buffer.from(await res.arrayBuffer()));
      GlobalFonts.registerFromPath(p, "NotoSansJP");
    }
  } catch { /* no font — boxes for JP text */ }
}

// ── Jacket cache ──────────────────────────────────────────────────────────────
const JACKET_DIR = path.join(process.cwd(), ".next", "cache", "jackets");
const jacketMem  = new Map<string, Buffer | null>();
// A miss is remembered briefly (not for the process lifetime) so a Sega/mirror outage can recover.
const jacketMissAt = new Map<string, number>();
const JACKET_MISS_TTL_MS = 10 * 60 * 1000;
const MOBILE_UA = "Mozilla/5.0 (iPhone; CPU iPhone OS 17_0 like Mac OS X) AppleWebKit/605.1.15";

async function tryFetchImage(src: string, headers: Record<string, string>): Promise<Buffer | null> {
  try {
    const res = await fetch(src, { headers, signal: AbortSignal.timeout(8_000) });
    return res.ok ? Buffer.from(await res.arrayBuffer()) : null;
  } catch { return null; }
}

async function fetchJacket(url: string, token: string, region: "intl" | "jp"): Promise<Buffer | null> {
  if (!url) return null;
  if (jacketMem.has(url)) {
    const cached = jacketMem.get(url)!;
    if (cached || Date.now() - (jacketMissAt.get(url) ?? 0) < JACKET_MISS_TTL_MS) return cached;
  }
  const disk = path.join(JACKET_DIR, url.replace(/[^a-zA-Z0-9._-]/g, "_"));
  try { const b = await fs.readFile(disk); jacketMem.set(url, b); return b; } catch { /* miss */ }

  // Same order as the web client (lib/jacket.ts): community mirror first, then Sega with the session cookie
  const base = region === "intl" ? "https://maimaidx-eng.com/maimai-mobile" : "https://maimaidx.jp/maimai-mobile";
  const cookie = token.includes("=") ? token : (region === "intl" ? `_t=${token}` : `clal=${token}`);
  const buf =
    await tryFetchImage(`${OTOGE_DB_JACKET_BASE}/${url}`, { "User-Agent": MOBILE_UA }) ??
    await tryFetchImage(`${base}/img/Music/${url}`, { Cookie: cookie, "User-Agent": MOBILE_UA, Referer: `${base}/` });

  if (!buf) { jacketMem.set(url, null); jacketMissAt.set(url, Date.now()); return null; }
  await fs.mkdir(JACKET_DIR, { recursive: true }).catch(() => {});
  await fs.writeFile(disk, buf).catch(() => {});
  jacketMem.set(url, buf);
  jacketMissAt.delete(url);
  return buf;
}

async function prefetch(urls: string[], token: string, region: "intl" | "jp") {
  const needed = [...new Set(urls.filter(Boolean))].filter(u => !jacketMem.get(u));
  for (let i = 0; i < needed.length; i += 8)
    await Promise.all(needed.slice(i, i + 8).map(u => fetchJacket(u, token, region)));
}

// ── Type badge images (music_dx.webp / music_standard.webp from /public/badges) ──
type ImageData = Awaited<ReturnType<typeof loadImage>>;
const typeBadgeCache: Record<"DX" | "STD", ImageData | null> = { DX: null, STD: null };

async function loadTypeBadges(): Promise<void> {
  const base = path.join(process.cwd(), "public", "badges");
  try {
    if (!typeBadgeCache.DX)  typeBadgeCache.DX  = await loadImage(path.join(base, "music_dx.webp"));
    if (!typeBadgeCache.STD) typeBadgeCache.STD  = await loadImage(path.join(base, "music_standard.webp"));
  } catch { /* badges not found — fall back to text pill */ }
}

// ── Helpers ───────────────────────────────────────────────────────────────────
function rr(ctx: SKRSContext2D, x: number, y: number, w: number, h: number, r: number) {
  if (w < 2 * r) r = w / 2; if (h < 2 * r) r = h / 2;
  ctx.beginPath();
  ctx.moveTo(x + r, y); ctx.arcTo(x + w, y, x + w, y + h, r);
  ctx.arcTo(x + w, y + h, x, y + h, r); ctx.arcTo(x, y + h, x, y, r);
  ctx.arcTo(x, y, x + w, y, r); ctx.closePath();
}

function trunc(ctx: SKRSContext2D, text: string, maxW: number): string {
  if (ctx.measureText(text).width <= maxW) return text;
  let t = text;
  while (t.length > 0 && ctx.measureText(t + "…").width > maxW) t = t.slice(0, -1);
  return t + "…";
}

// ── Score card ────────────────────────────────────────────────────────────────
async function drawCard(
  ctx: SKRSContext2D, score: ScoreWithRating,
  x: number, y: number, token: string, region: "intl" | "jp",
) {
  const t      = CARD_THEME[score.difficulty] ?? CARD_THEME.MAS;
  const accent = DIFF_ACCENT[score.difficulty] ?? "#a78bfa";
  const ach    = typeof score.achievement === "string" ? parseFloat(score.achievement) : (score.achievement as number);

  ctx.save();

  // ━━━━━━━━━━━━━━ Body + title strip (clipped to the rounded card) ━━━━━━━━━━━
  rr(ctx, x, y, CARD_W, CARD_H, CR);
  ctx.save();
  ctx.clip();
  ctx.fillStyle = t.body;  ctx.fillRect(x, y, CARD_W, CA);
  ctx.fillStyle = t.strip; ctx.fillRect(x, y + CA, CARD_W, CT);
  ctx.restore();

  // ━━━━━━━━━━━━━━ Jacket — square, inset, rounded ━━━━━━━━━━━━━━━━━━━━━━━━━━━
  const jx = x + JP, jy = y + JP;
  const imgBuf = score.song?.image_url ? await fetchJacket(score.song.image_url, token, region) : null;
  let drewJacket = false;
  if (imgBuf) {
    try {
      const img = await loadImage(imgBuf);
      ctx.save();
      rr(ctx, jx, jy, JS, JS, 3); ctx.clip();
      ctx.drawImage(img, jx, jy, JS, JS);
      ctx.restore();
      drewJacket = true;
    } catch { /* fallback below */ }
  }
  if (!drewJacket) {
    const g = ctx.createLinearGradient(jx, jy, jx + JS, jy + JS);
    g.addColorStop(0, accent + "66"); g.addColorStop(1, accent + "22");
    rr(ctx, jx, jy, JS, JS, 3); ctx.fillStyle = g; ctx.fill();
  }

  // ━━━━━━━━━━━━━━ Middle — type badge, rank, achievement + FC/FS ━━━━━━━━━━━━━
  const mx = jx + JS + 6;
  const rbx = x + CARD_W - JP - RB_W;   // rating box left edge

  // Type badge — same image from /public/badges used by the scores page; text pill fallback.
  const isDX     = score.songType !== "STD";
  const badgeImg = isDX ? typeBadgeCache.DX : typeBadgeCache.STD;
  const pillH    = 11;
  if (badgeImg) {
    const pillW = Math.round(pillH * badgeImg.width / badgeImg.height);
    ctx.drawImage(badgeImg, mx, y + 6, pillW, pillH);
  } else {
    const typeStr = isDX ? "でらっくす" : "スタンダード";
    ctx.font = F(6);
    const pillW = ctx.measureText(typeStr).width + 8;
    rr(ctx, mx, y + 6, pillW, pillH, 3);
    ctx.fillStyle = "#ffffff"; ctx.fill();
    ctx.fillStyle = isDX ? "#e9407a" : "#3b82f6";
    ctx.textAlign = "left"; ctx.textBaseline = "middle";
    ctx.fillText(typeStr, mx + 4, y + 6 + pillH / 2);
  }

  // Rank — per-letter colours with a dark outline; auto-shrinks to fit before the rating box
  const glyphs = RANK_GLYPHS[score.rank] ?? [["?", "#ffffff"] as RankGlyph];
  const maxRankW = rbx - mx - 4;
  let rankPx = 21;
  const measureGlyphs = (px: number) => {
    let w = 0;
    for (const [ch, , isPlus] of glyphs) {
      ctx.font = FH(isPlus ? Math.round(px * 0.6) : px);
      w += ctx.measureText(ch).width;
    }
    return w;
  };
  while (rankPx > 10 && measureGlyphs(rankPx) > maxRankW) rankPx--;

  const plusPx = Math.round(rankPx * 0.6);
  const baseY  = y + 40;
  ctx.textAlign = "left"; ctx.textBaseline = "alphabetic";
  ctx.lineJoin  = "round";
  let gx = mx;
  for (const [ch, color, isPlus] of glyphs) {
    ctx.font = FH(isPlus ? plusPx : rankPx);
    const gy = isPlus ? baseY - Math.round(rankPx * 0.4) : baseY;
    ctx.strokeStyle = "rgba(35,22,50,0.85)"; ctx.lineWidth = 2.4;
    ctx.strokeText(ch, gx, gy);
    ctx.fillStyle = color; ctx.fillText(ch, gx, gy);
    gx += ctx.measureText(ch).width;
  }

  // Achievement %
  ctx.font = F(11.5);
  ctx.fillStyle = t.text;
  ctx.textAlign = "left"; ctx.textBaseline = "alphabetic";
  ctx.fillText(`${ach.toFixed(4)}%`, mx, y + 61);

  // ━━━━━━━━━━━━━━ Rating box — top right ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
  rr(ctx, rbx, y + JP, RB_W, RB_H, 4);
  ctx.fillStyle = t.ratingBg; ctx.fill();
  ctx.font = F(22); ctx.fillStyle = t.ratingFg;
  ctx.textAlign = "center"; ctx.textBaseline = "middle";
  ctx.fillText(String(score.rating), rbx + RB_W / 2, y + JP + RB_H / 2 + 1);

  // FC / FS badges — under the rating box, right-aligned to it, only when earned
  const badges = [score.fc ? FC_C[score.fc] : undefined, score.fs ? FS_C[score.fs] : undefined]
    .filter((b): b is BadgeStyle => !!b);
  const bh = 14, by = y + JP + RB_H + 4, bgap = 3;
  const badgeW = (b: BadgeStyle) => {
    ctx.font = F(8);
    const lw = ctx.measureText(b.label).width;
    ctx.font = F(6);
    const pw = b.plus ? ctx.measureText("+").width : 0;
    return { lw, pw, bw: Math.max(20, lw + pw + 8) };
  };
  const sizes = badges.map(badgeW);
  let bx = rbx + RB_W - (sizes.reduce((sum, m) => sum + m.bw, 0) + bgap * Math.max(0, sizes.length - 1));
  badges.forEach((b, k) => {
    const { lw, pw, bw } = sizes[k];
    rr(ctx, bx, by, bw, bh, 2.5);
    ctx.fillStyle = t.light ? b.deep : b.pastel; ctx.fill();
    ctx.strokeStyle = b.border; ctx.lineWidth = 1.2; ctx.stroke();
    const lx = bx + (bw - lw - pw) / 2;
    ctx.fillStyle = t.light ? b.pastel : b.ink;
    ctx.textAlign = "left"; ctx.textBaseline = "middle";
    ctx.font = F(8); ctx.fillText(b.label, lx, by + bh / 2 + 0.5);
    if (b.plus) { ctx.font = F(6); ctx.fillText("+", lx + lw, by + bh / 2 - 2.5); }
    bx += bw + bgap;
  });

  // ━━━━━━━━━━━━━━ Title strip — song title + level box flush bottom-right ━━━━━━
  const lvTxt = score.internalLevel > 0 ? score.internalLevel.toFixed(1) : "?";
  ctx.font = F(10.5);
  const lvW = Math.max(32, ctx.measureText(lvTxt).width + 12);
  const lvX = x + CARD_W - lvW, lvY = y + CA;
  // Rounded top-left; bottom-right follows the card corner
  ctx.beginPath();
  ctx.moveTo(lvX + 4, lvY); ctx.lineTo(lvX + lvW, lvY);
  ctx.lineTo(lvX + lvW, lvY + CT - CR); ctx.arcTo(lvX + lvW, lvY + CT, lvX + lvW - CR, lvY + CT, CR);
  ctx.lineTo(lvX, lvY + CT); ctx.lineTo(lvX, lvY + 4); ctx.arcTo(lvX, lvY, lvX + 4, lvY, 4);
  ctx.closePath();
  ctx.fillStyle = t.levelBg; ctx.fill();
  ctx.textAlign = "center"; ctx.textBaseline = "middle";
  ctx.fillStyle = t.levelFg;
  ctx.fillText(lvTxt, lvX + lvW / 2, lvY + CT / 2 + 0.5);

  ctx.font = F(9.5);
  ctx.fillStyle = t.text;
  ctx.textAlign = "left"; ctx.textBaseline = "middle";
  ctx.fillText(trunc(ctx, score.songTitle, lvX - x - 10), x + 6, y + CA + CT / 2 + 0.5);

  ctx.textAlign    = "left";
  ctx.textBaseline = "alphabetic";
  ctx.restore();
}

// ── Section header — short pill: label left, rating total right ──────────────
const HEADER_W = Math.round(CARD_W * 1.5 + CARD_GAP);
const HEADER_H = 24;
function drawHeader(
  ctx: SKRSContext2D, label: string, total: number,
  x: number, y: number, colors: { bg: string; fg: string },
) {
  rr(ctx, x, y, HEADER_W, HEADER_H, 4);
  ctx.fillStyle = colors.bg; ctx.fill();
  ctx.fillStyle = colors.fg; ctx.textBaseline = "middle";
  ctx.font = F(12.5); ctx.textAlign = "left";
  ctx.fillText(label, x + 10, y + HEADER_H / 2 + 0.5);
  ctx.font = F(13); ctx.textAlign = "right";
  ctx.fillText(String(total), x + HEADER_W - 10, y + HEADER_H / 2 + 0.5);
  ctx.textAlign = "left"; ctx.textBaseline = "alphabetic";
}

// ── Profile header ────────────────────────────────────────────────────────────
export interface B50Profile {
  name: string | null;
  avatar: string | null;
  rating?: string | null;
  title?: string | null;        // trophy
  totalPlays?: string | null;
  versionPlays?: string | null;
  courseRank?: string | null;   // Dan icon URL
  classRank?: string | null;    // Class icon URL
  ratingBase?: string | null;   // in-game rating plate URL
}

// Avatar / Dan / Class / rating plate are Sega-hosted; a failed fetch is retried after JACKET_MISS_TTL_MS.
const profileImgMem = new Map<string, { img: ImageData | null; at: number }>();
async function fetchProfileImage(url: string | null | undefined): Promise<ImageData | null> {
  if (!url) return null;
  const hit = profileImgMem.get(url);
  if (hit && (hit.img || Date.now() - hit.at < JACKET_MISS_TTL_MS)) return hit.img;
  const buf = await tryFetchImage(url, { "User-Agent": MOBILE_UA });
  let img: ImageData | null = null;
  if (buf) { try { img = await loadImage(buf); } catch { /* not an image */ } }
  profileImgMem.set(url, { img, at: Date.now() });
  return img;
}

/** Text with extra space between characters (canvas letterSpacing isn't reliable across versions). Returns the end x. */
function spacedText(ctx: SKRSContext2D, text: string, x: number, y: number, spacing: number, maxW: number): number {
  let cx = x;
  for (const ch of text) {
    const w = ctx.measureText(ch).width;
    if (cx + w - x > maxW) { ctx.fillText("…", cx, y); return cx + ctx.measureText("…").width; }
    ctx.fillText(ch, cx, y);
    cx += w + spacing;
  }
  return cx - spacing;
}

// Digit slots on rating_base_*.png (296x86): five ~31.4px slots from x=123.5, vertical centre y=42
const PLATE_W = 296, PLATE_H = 86, PLATE_SLOT_X = 123.5, PLATE_SLOT_W = 31.4, PLATE_SLOT_CY = 42;

function drawRatingDigits(ctx: SKRSContext2D, rating: number, x: number, cy: number, slotW: number, px: number) {
  const digits = String(rating).padStart(5, " ").slice(-5);
  ctx.font = F(px); ctx.textAlign = "center"; ctx.textBaseline = "middle";
  ctx.lineJoin = "round"; ctx.lineWidth = px * 0.22; ctx.strokeStyle = "#5a3200";
  for (let i = 0; i < 5; i++) {
    const d = digits[i];
    if (d === " ") continue;
    const dx = x + slotW * (i + 0.5);
    ctx.strokeText(d, dx, cy + 1);
    ctx.fillStyle = "#ffd84a"; ctx.fillText(d, dx, cy + 1);
  }
}

async function drawProfileHeader(ctx: SKRSContext2D, profile: B50Profile, ratingData: RatingData, x: number, y: number) {
  const [avatar, dan, klass, plate] = await Promise.all([
    fetchProfileImage(profile.avatar), fetchProfileImage(profile.courseRank),
    fetchProfileImage(profile.classRank), fetchProfileImage(profile.ratingBase),
  ]);

  rr(ctx, x, y, GRID_W, PROFILE_H, 8);
  ctx.fillStyle = C.profileBg; ctx.fill();
  ctx.strokeStyle = C.profileBorder; ctx.lineWidth = 1; ctx.stroke();

  // ── Avatar ──
  const asz = PROFILE_H - 16, ax = x + 8, ay = y + 8;
  ctx.save();
  rr(ctx, ax, ay, asz, asz, 8); ctx.clip();
  const ag = ctx.createLinearGradient(ax, ay, ax + asz, ay + asz);
  ag.addColorStop(0, "#3b2d6e"); ag.addColorStop(1, "#1a1530");
  ctx.fillStyle = ag; ctx.fillRect(ax, ay, asz, asz);
  if (avatar) ctx.drawImage(avatar, ax, ay, asz, asz);
  ctx.restore();

  // ── Rating plate (right) ──
  const ph = 54, pw = Math.round(ph * PLATE_W / PLATE_H);
  const px = x + GRID_W - 12 - pw, py = y + (PROFILE_H - ph) / 2;
  const k = ph / PLATE_H;
  if (plate) {
    ctx.drawImage(plate, px, py, pw, ph);
    drawRatingDigits(ctx, ratingData.totalRating, px + PLATE_SLOT_X * k, py + PLATE_SLOT_CY * k, PLATE_SLOT_W * k, 21);
  } else {
    const bw = PLATE_SLOT_W * k * 5 + 12;
    rr(ctx, x + GRID_W - 12 - bw, py + 8, bw, ph - 16, 7);
    ctx.fillStyle = "#2a2a2a"; ctx.fill();
    ctx.strokeStyle = C.profileLine; ctx.lineWidth = 1; ctx.stroke();
    drawRatingDigits(ctx, ratingData.totalRating, x + GRID_W - 6 - bw, py + ph / 2, PLATE_SLOT_W * k, 21);
  }

  // ── Name + trophy title ──
  const tx = ax + asz + 16;
  const maxTextW = px - tx - 16;
  ctx.textAlign = "left"; ctx.textBaseline = "alphabetic";
  ctx.font = F(21); ctx.fillStyle = C.profileFg;
  const nameEnd = spacedText(ctx, profile.name ?? "Player", tx, y + 32, 6, Math.min(300, maxTextW));
  if (profile.title) {
    ctx.font = F(10);
    const tpx = nameEnd + 14, tpy = y + 15;
    const tw = Math.min(ctx.measureText(profile.title).width + 16, tx + maxTextW - tpx);
    if (tw > 40) {
      rr(ctx, tpx, tpy, tw, 20, 10);
      ctx.fillStyle = C.profilePill; ctx.fill();
      ctx.fillStyle = C.profileMuted; ctx.textBaseline = "middle";
      ctx.fillText(trunc(ctx, profile.title, tw - 16), tpx + 8, tpy + 10.5);
      ctx.textBaseline = "alphabetic";
    }
  }

  // ── Stat columns ──
  type Stat = { label: string; draw: (cx: number, cy: number) => void };
  const textValue = (v: string, color = C.profileFg) => (cx: number, cy: number) => {
    ctx.font = F(14); ctx.fillStyle = color; ctx.textBaseline = "middle"; ctx.fillText(v, cx, cy);
  };
  const imageValue = (img: ImageData) => (cx: number, cy: number) => {
    const h = 24, w = h * img.width / img.height;
    ctx.drawImage(img, cx - 2, cy - h / 2, w, h);
  };
  const stats: Stat[] = [];
  if (profile.totalPlays) {
    const version = profile.versionPlays && profile.versionPlays !== profile.totalPlays ? ` (${profile.versionPlays})` : "";
    stats.push({ label: "Plays", draw: textValue(profile.totalPlays + version) });
  }
  if (dan)   stats.push({ label: "Dan",   draw: imageValue(dan) });
  if (klass) stats.push({ label: "Class", draw: imageValue(klass) });
  stats.push({ label: "New", draw: textValue(String(ratingData.newRating), C.profileNew) });
  stats.push({ label: "Old", draw: textValue(String(ratingData.oldRating), C.profileOld) });

  const colW = 92, labelY = y + 50, valueY = y + 68;
  stats.forEach((st, i) => {
    const cx = tx + i * colW;
    if (cx + colW > px - 8) return;
    if (i > 0) {
      ctx.strokeStyle = C.profileLine; ctx.lineWidth = 1;
      ctx.beginPath(); ctx.moveTo(cx - 10, labelY - 8); ctx.lineTo(cx - 10, valueY + 10); ctx.stroke();
    }
    ctx.font = F(9); ctx.fillStyle = C.profileMuted; ctx.textBaseline = "alphabetic";
    ctx.fillText(st.label, cx, labelY);
    st.draw(cx, valueY);
  });
  ctx.textAlign = "left"; ctx.textBaseline = "alphabetic";
}

function drawFooter(ctx: SKRSContext2D) {
  ctx.textAlign = "right"; ctx.textBaseline = "alphabetic";
  ctx.font = F(9); ctx.fillStyle = C.sfgMuted;
  ctx.fillText(`generated by moimoi · ${formatIsoDate(new Date())}`, W - PAD, H - 7);
  ctx.textAlign = "left";
}

// ── Exports ───────────────────────────────────────────────────────────────────
export interface B50GenerateOptions {
  ratingData: RatingData;
  profile: B50Profile;
  token: string;
  region: "intl" | "jp";
}

export async function generateB50Image(opts: B50GenerateOptions): Promise<Buffer> {
  const { ratingData, profile, token, region } = opts;
  await setupFonts();
  await loadTypeBadges();

  const canvas = createCanvas(W * SCALE, H * SCALE);
  const ctx    = canvas.getContext("2d");
  ctx.scale(SCALE, SCALE);

  const bg = ctx.createLinearGradient(0, 0, 0, H);
  bg.addColorStop(0, C.bgTop); bg.addColorStop(1, C.bgBottom);
  ctx.fillStyle = bg; ctx.fillRect(0, 0, W, H);

  await prefetch([
    ...ratingData.newCharts.map(s => s.song?.image_url ?? ""),
    ...ratingData.oldCharts.map(s => s.song?.image_url ?? ""),
  ], token, region);

  const cx = PAD;
  let cy   = PAD;
  await drawProfileHeader(ctx, profile, ratingData, cx, cy);
  cy += PROFILE_H + 12;

  const newTotal = ratingData.newCharts.reduce((s, c) => s + c.rating, 0);
  drawHeader(ctx, "New B15", newTotal, cx, cy, C.headerNew);
  cy += 28;
  for (let i = 0; i < ratingData.newCharts.length; i++) {
    const col = i % COLS, row = Math.floor(i / COLS);
    await drawCard(ctx, ratingData.newCharts[i],
      cx + col * (CARD_W + CARD_GAP), cy + row * (CARD_H + CARD_GAP), token, region);
  }
  cy += Math.ceil(Math.max(ratingData.newCharts.length, 1) / COLS) * (CARD_H + CARD_GAP) + 10;

  const oldTotal = ratingData.oldCharts.reduce((s, c) => s + c.rating, 0);
  drawHeader(ctx, "Old B35", oldTotal, cx, cy, C.headerOld);
  cy += 28;
  for (let i = 0; i < ratingData.oldCharts.length; i++) {
    const col = i % COLS, row = Math.floor(i / COLS);
    await drawCard(ctx, ratingData.oldCharts[i],
      cx + col * (CARD_W + CARD_GAP), cy + row * (CARD_H + CARD_GAP), token, region);
  }

  drawFooter(ctx);
  return canvas.toBuffer("image/png");
}